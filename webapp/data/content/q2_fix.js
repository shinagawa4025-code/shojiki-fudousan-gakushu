  const MONTH = /([0-9０-９一二三四五六七八九十百何数〜～])[ヶケカヵ]月/g;
  const fixMonth = (s) => (typeof s === `string` ? s.replace(MONTH, `$1か月`) : s);
  const stripVerdict = (n) => String(n || ``)
